"""CLI: ``python -m planagent {ask, eval, build-db}``."""

from __future__ import annotations

import argparse
import json
import sys

from .data import ROOT, build_db
from .report import md_table


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(prog="planagent", description="Auditable AI agent for scenario analysis.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("ask", help="answer one question")
    a.add_argument("question")
    for p in (a, sub.add_parser("eval", help="run the evaluation suite and write reports/")):
        p.add_argument("--backend", default="scripted", choices=["scripted", "anthropic", "bedrock"])
        p.add_argument("--model", default=None)
    sub.add_parser("build-db", help="rebuild data/planagent.db from data/raw")
    args = ap.parse_args(argv)

    if args.cmd == "build-db":
        print(f"built {build_db()}")
        return
    from .llm import make_backend

    backend = make_backend(args.backend, args.model)
    if args.cmd == "ask":
        from .agent import Agent

        r = Agent(backend).run(args.question)
        print(r.answer)
        print(f"\n[{r.status}] {r.guardrail.summary()}\n[audit] {r.audit_path}", file=sys.stderr)
        return
    from . import evals

    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    tasks, runs = evals.run_tasks(backend, audit_dir=ROOT / "runs")
    gr = evals.red_team_guardrail(runs)
    sq = evals.red_team_sql()
    rt, misses = evals.retrieval_eval()
    tag = f"{backend.name}" + (f" ({backend.model})" if backend.model else "")
    md = [
        f"# PlanAgent evaluation: backend {tag}",
        "",
        "Generated by `python -m planagent eval`. The scripted backend is a deterministic rule-based planner, "
        "not a language model: it validates tools, guardrails and audit end to end. Run with "
        "`--backend anthropic` or `--backend bedrock` to evaluate a live model on the same tasks.",
        "",
        "## 1. End-to-end tasks",
        "",
        md_table(tasks, 2),
        "",
        f"Tasks: {len(tasks)}; tools as expected {tasks['tools as expected'].mean():.0%}, answers correct "
        f"against independent ground truth {tasks['answer correct'].mean():.0%}, guardrail pass "
        f"{tasks['guardrail pass'].mean():.0%}.",
        "",
        "## 2. Guardrail red team (numeric provenance)",
        "",
        "Every number in every released answer is perturbed by the factor shown (formatted at the same "
        "precision) and the guardrail is re-run with the same tool outputs; 'invented sentence' appends an "
        "unsupported claim.",
        "",
        md_table(gr, 3),
        "",
        "## 3. SQL red team",
        "",
        md_table(sq, 2),
        "",
        "## 4. Retrieval (BM25 over the knowledge base)",
        "",
        md_table(rt, 3),
        "",
    ]
    if misses:
        md += ["Not ranked first:", "", md_table(__import__("pandas").DataFrame(misses), index=False), ""]
    (out / "evals.md").write_text("\n".join(md) + "\n")
    (out / "transcripts.md").write_text(
        f"# Transcripts: backend {tag}\n\n" + "\n".join(evals.transcript(t, r) for t, r in runs)
    )
    (out / "evals.json").write_text(
        json.dumps(
            {
                "backend": tag,
                "tasks": tasks.reset_index().to_dict(orient="records"),
                "guardrail_red_team": gr.reset_index().to_dict(orient="records"),
                "sql_red_team": sq.reset_index().to_dict(orient="records"),
                "retrieval": rt["value"].to_dict(),
            },
            indent=2,
            default=str,
        )
    )
    print((out / "evals.md").read_text())


if __name__ == "__main__":
    main()
